export function resolveDataTableLabels(
  overrides?: DataTableLabelOverrides,
): DataTableLabels {
  if (!overrides) return dataTableLabels;
  return {
    ...dataTableLabels,
    ...overrides,
    operators: { ...dataTableLabels.operators, ...overrides.operators },
  } as DataTableLabels;
}
